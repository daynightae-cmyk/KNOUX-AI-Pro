package com.knoux.ai.developer.vault

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Log
import com.knoux.ai.developer.model.ProviderConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Secure API Key Vault.
 *
 * All credentials are encrypted with AES-256-GCM using a key that never leaves
 * Android Keystore. The IV is generated by Keystore for every encryption
 * (`setRandomizedEncryptionRequired(true)`), so nonces are never reused even if
 * the app process is cloned. SharedPreferences store only the Base64
 * `IV || ciphertext || tag` blob and a masked display value.
 *
 * Failure handling:
 *  - a missing/invalidated Keystore key makes [getCredential] return null and
 *    removes the unreadable ciphertext instead of silently returning garbage,
 *  - [wipeAll] is the explicit recovery path after a device restore or key
 *    invalidation (the user must re-enter the key).
 *
 * Biometric re-authentication is a UI gate in [BiometricGate]; decryption itself
 * is only callable by app code and never logs plaintext.
 */
class CredentialVault(private val context: Context) {

    private companion object {
        const val TAG = "KnouxVault"
        const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
        const val GCM_IV_LENGTH = 12
        const val GCM_TAG_BITS = 128
        const val PREFS_NAME = "knoux_developer_vault"
        const val ENC_KEY_PREFIX = "enc_"
        const val MASKED_KEY_PREFIX = "masked_"
        const val ENABLED_KEY_PREFIX = "enabled_"
        const val MASTER_KEY_ALIAS = "knoux_developer_vault_master_v2"
    }

    private val masterKeyAlias: String = MASTER_KEY_ALIAS
    private val vaultPrefs: android.content.SharedPreferences =
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)

    init {
        ensureMasterKey()
    }

    /** Create the AES-256-GCM master key if it does not exist. */
    private fun ensureMasterKey() {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER)
        keyStore.load(null)
        if (keyStore.containsAlias(masterKeyAlias)) return

        val keyGen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER)
        keyGen.init(
            KeyGenParameterSpec.Builder(
                masterKeyAlias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                // Keystore generates a fresh random IV for every encryption.
                .setRandomizedEncryptionRequired(true)
                .build(),
        )
        keyGen.generateKey()
    }

    /** Encrypt a plaintext API key and return the Base64-encoded IV + ciphertext. */
    fun encrypt(apiKey: String): String {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER)
        keyStore.load(null)
        val secretKey = keyStore.getKey(masterKeyAlias, null) as SecretKey

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)
        val iv = cipher.iv
        require(iv.size == GCM_IV_LENGTH) { "Unexpected GCM IV length" }

        val ciphertext = cipher.doFinal(apiKey.toByteArray(Charsets.UTF_8))
        val combined = ByteArray(iv.size + ciphertext.size)
        System.arraycopy(iv, 0, combined, 0, iv.size)
        System.arraycopy(ciphertext, 0, combined, iv.size, ciphertext.size)

        return android.util.Base64.encodeToString(combined, android.util.Base64.NO_WRAP)
    }

    /** Decrypt a Base64-encoded ciphertext back to the plaintext API key. */
    fun decrypt(ciphertextB64: String): String {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER)
        keyStore.load(null)
        val secretKey = keyStore.getKey(masterKeyAlias, null) as SecretKey
            ?: throw IllegalStateException("Keystore master key is unavailable")

        val combined = android.util.Base64.decode(ciphertextB64, android.util.Base64.NO_WRAP)
        require(combined.size > GCM_IV_LENGTH) { "Invalid vault blob" }
        val iv = ByteArray(GCM_IV_LENGTH)
        System.arraycopy(combined, 0, iv, 0, GCM_IV_LENGTH)
        val ciphertext = ByteArray(combined.size - GCM_IV_LENGTH)
        System.arraycopy(combined, GCM_IV_LENGTH, ciphertext, 0, ciphertext.size)

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(GCM_TAG_BITS, iv))
        return String(cipher.doFinal(ciphertext), Charsets.UTF_8)
    }

    /** Mask a key for display: show only first 4 and last 4 chars. */
    fun maskKey(apiKey: String): String {
        if (apiKey.length <= 8) return "****"
        return apiKey.substring(0, 4) + "****" + apiKey.substring(apiKey.length - 4)
    }

    /** Store a provider credential (encrypted) and masked display value. */
    suspend fun storeCredential(config: ProviderConfig, plaintextKey: String) {
        withContext(Dispatchers.IO) {
            val encrypted = encrypt(plaintextKey)
            val committed = vaultPrefs.edit()
                .putString("${ENC_KEY_PREFIX}${config.providerId}", encrypted)
                .putString("${MASKED_KEY_PREFIX}${config.providerId}", maskKey(plaintextKey))
                .putBoolean("${ENABLED_KEY_PREFIX}${config.providerId}", config.isEnabled)
                .commit()
            check(committed) { "Could not persist credential" }
        }
    }

    /**
     * Retrieve and decrypt a provider credential.
     * Returns null when the entry is missing or the Keystore key was invalidated;
     * an unreadable entry is deleted so it cannot cause repeated failures.
     */
    suspend fun getCredential(providerId: String): String? {
        return withContext(Dispatchers.IO) {
            val encrypted = vaultPrefs.getString("${ENC_KEY_PREFIX}$providerId", null) ?: return@withContext null
            try {
                decrypt(encrypted)
            } catch (failure: Exception) {
                Log.w(TAG, "Credential unreadable for $providerId: ${failure.javaClass.simpleName}")
                vaultPrefs.edit()
                    .remove("${ENC_KEY_PREFIX}$providerId")
                    .remove("${MASKED_KEY_PREFIX}$providerId")
                    .commit()
                null
            }
        }
    }

    /** Masked key for display (no decryption needed). */
    fun getMaskedKey(providerId: String): String =
        vaultPrefs.getString("${MASKED_KEY_PREFIX}$providerId", null) ?: "****"

    fun getMaskedKey(config: ProviderConfig): String = getMaskedKey(config.providerId)

    /** Check whether a credential exists for the provider. */
    fun hasCredential(providerId: String): Boolean =
        vaultPrefs.getString("${ENC_KEY_PREFIX}$providerId", null) != null

    /** Remove a provider credential and its display metadata. */
    suspend fun removeCredential(providerId: String) {
        withContext(Dispatchers.IO) {
            val committed = vaultPrefs.edit()
                .remove("${ENC_KEY_PREFIX}$providerId")
                .remove("${MASKED_KEY_PREFIX}$providerId")
                .remove("${ENABLED_KEY_PREFIX}$providerId")
                .commit()
            check(committed) { "Could not delete credential" }
        }
    }

    /** Enable/disable a credential. */
    suspend fun setEnabled(providerId: String, enabled: Boolean) {
        withContext(Dispatchers.IO) {
            vaultPrefs.edit().putBoolean("${ENABLED_KEY_PREFIX}$providerId", enabled).commit()
        }
    }

    fun isEnabled(providerId: String): Boolean =
        vaultPrefs.getBoolean("${ENABLED_KEY_PREFIX}$providerId", false)

    /**
     * Explicit recovery: delete every encrypted value and masked label. The
     * Keystore key is kept (deleting it would also invalidate any other data
     * using it) so the user can re-enter credentials safely.
     */
    suspend fun wipeAll() {
        withContext(Dispatchers.IO) {
            val editor = vaultPrefs.edit()
            vaultPrefs.all.keys
                .filter {
                    it.startsWith(ENC_KEY_PREFIX) ||
                        it.startsWith(MASKED_KEY_PREFIX) ||
                        it.startsWith(ENABLED_KEY_PREFIX)
                }
                .forEach { editor.remove(it) }
            editor.commit()
        }
    }

    /** Never log real keys. */
    fun safeLogKey(providerId: String): String = "***REDACTED***"
}

/**
 * Biometric gate for credential viewing/exporting.
 * Returns true only after the user authenticates with biometrics or the device
 * credential. This is a UI gate; callers must not decrypt before it succeeds.
 */
class BiometricGate private constructor(private val activity: androidx.fragment.app.FragmentActivity) {

    companion object {
        fun authenticate(
            activity: androidx.fragment.app.FragmentActivity,
            onResult: (Boolean) -> Unit,
        ) {
            val executor = androidx.core.content.ContextCompat.getMainExecutor(activity)
            val prompt = androidx.biometric.BiometricPrompt(
                activity,
                executor,
                object : androidx.biometric.BiometricPrompt.AuthenticationCallback() {
                    override fun onAuthenticationSucceeded(
                        result: androidx.biometric.BiometricPrompt.AuthenticationResult,
                    ) {
                        onResult(true)
                    }

                    override fun onAuthenticationError(errorCode: Int, errString: CharSequence) {
                        onResult(false)
                    }

                    override fun onAuthenticationFailed() {
                        // System keeps the prompt open; report only on final error.
                    }
                },
            )

            val info = androidx.biometric.BiometricPrompt.PromptInfo.Builder()
                .setTitle("تأكيد الهوية")
                .setDescription("يُطلب التحقق لعرض المفتاح. لا يُسجَّل المفتاح في السجلات.")
                .setAllowedAuthenticators(
                    androidx.biometric.BiometricManager.Authenticators.BIOMETRIC_STRONG or
                        androidx.biometric.BiometricManager.Authenticators.DEVICE_CREDENTIAL,
                )
                .build()

            prompt.authenticate(info)
        }
    }
}
